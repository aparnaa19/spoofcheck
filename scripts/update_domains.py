#!/usr/bin/env python3
"""Rebuild data/federal-domains.js from CISA's .gov domain list.

Source: https://github.com/cisagov/dotgov-data (current-full.csv)
Keeps only "Federal - Executive" domains, the ones BOD 18-01 applies to.

Usage:  python3 scripts/update_domains.py
Standard library only.
"""
import csv
import datetime
import io
import json
import os
import urllib.request

SOURCE = "https://raw.githubusercontent.com/cisagov/dotgov-data/main/current-full.csv"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "federal-domains.js")


def main():
    raw = urllib.request.urlopen(SOURCE, timeout=60).read().decode("utf-8")
    rows = [
        [r["Domain name"].strip().lower(), r["Organization name"].strip(), r["Suborganization name"].strip()]
        for r in csv.DictReader(io.StringIO(raw))
        if r["Domain type"] == "Federal - Executive"
    ]
    rows.sort(key=lambda r: (r[1], r[0]))

    meta = {"source": SOURCE, "fetched": datetime.date.today().isoformat(), "count": len(rows)}
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/update_domains.py. Columns: domain, organization, suborganization.\n")
        f.write("window.FEDERAL_META = " + json.dumps(meta) + ";\n")
        f.write("window.FEDERAL_DOMAINS = " + json.dumps(rows, separators=(",", ":")) + ";\n")
    print(f"wrote {len(rows)} domains to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
